"""Maintenance pass over the topic pages: a report and an overview. Never edits a topic page."""
import logging
from datetime import date, timedelta

from .llm import LLMError
from .pages import PageParseError, parse_page
from .vault import _TOPIC_LINK, TOPICS_DIR, append_log, keep_known_links, list_topics

log = logging.getLogger(__name__)
STALE_DAYS = 180

LINT_PROMPT = (
    "You review a personal knowledge base of topic pages (title, kind, description, summary). "
    "Reply with JSON only: {\"contradictions\": [...], \"merge_or_split\": [...], \"missing_topics\": [...], "
    "\"questions\": [...], \"overview\": \"<markdown>\"}. "
    "contradictions: claims that disagree between pages, naming both pages. "
    "merge_or_split: pages that overlap enough to merge, or cover too much and should split. "
    "missing_topics: topics that several pages mention but that have no page of their own. "
    "questions: a few questions worth investigating next. "
    "overview: a synthesis of the whole knowledge base in at most 400 words, linking pages exactly as "
    "[Title](<Topics/File.md>) using the file names given. Each list item is one sentence. Use empty lists when nothing applies."
)


def find_issues(pages: dict, today: date) -> dict[str, list[str]]:
    """Checks needing no LLM. pages: {"File.md": Page}."""
    inbound = {f: 0 for f in pages}
    for f, p in pages.items():
        for m in _TOPIC_LINK.finditer(f"{p.summary}\n{p.recent}"):
            target = m.group(2).removeprefix(f"{TOPICS_DIR}/")
            if target in inbound and target != f:
                inbound[target] += 1
    title = {f: str(p.front.get("title") or f.removesuffix(".md")) for f, p in pages.items()}
    cutoff = (today - timedelta(days=STALE_DAYS)).isoformat()
    return {
        "orphans": sorted(title[f] for f, n in inbound.items() if n == 0),
        "stale": sorted(f"{title[f]} (updated {p.front.get('updated')})" for f, p in pages.items()
                        if str(p.front.get("updated") or "") < cutoff),
        "no_description": sorted(title[f] for f, p in pages.items() if not p.front.get("description")),
    }


def run_lint(dav, llm, model: str, today: date) -> str:
    """Writes Maintenance/<date>.md and Overview.md; returns the report path."""
    pages = {}
    for t in list_topics(dav):
        try:
            pages[t.filename] = parse_page(dav.read(f"{TOPICS_DIR}/{t.filename}") or "")
        except PageParseError:
            continue
    issues = find_issues(pages, today)
    report = [f"# Maintenance {today.isoformat()}", "", f"{len(pages)} topic pages checked. Topic pages are never edited by this pass.", ""]
    for key, heading in (("orphans", "Pages nothing links to"), ("stale", f"Not updated for {STALE_DAYS} days"),
                         ("no_description", "Pages without a description")):
        report += [f"## {heading}", ""] + [f"- {x}" for x in issues[key]] + (["- none"] if not issues[key] else []) + [""]
    user = "\n\n".join(f"### {p.front.get('title')} → {f} ({p.front.get('kind') or 'unknown kind'})\n"
                       f"{p.front.get('description') or ''}\n{p.summary}" for f, p in sorted(pages.items()))
    try:
        reply = llm.chat_json(model, LINT_PROMPT, user)
        if not isinstance(reply, dict):
            raise LLMError("lint reply is not an object")
    except LLMError as e:
        log.warning("LLM review failed: %s", e)
        report += ["## LLM review failed", "", f"- {e}", ""]
        reply = None
    if reply:
        for key, heading in (("contradictions", "Contradictions"), ("merge_or_split", "Merge or split"),
                             ("missing_topics", "Missing topics"), ("questions", "Questions to explore")):
            items = [str(x) for x in reply.get(key) or [] if str(x).strip()]
            report += [f"## {heading}", ""] + [f"- {x}" for x in items] + (["- none"] if not items else []) + [""]
        if isinstance(reply.get("overview"), str) and reply["overview"].strip():
            allowed = {f"{TOPICS_DIR}/{f}" for f in pages}
            dav.write("Overview.md", f"# Overview\n\nGenerated by rss-digest lint on {today.isoformat()}; "
                      f"edits here are overwritten.\n\n{keep_known_links(reply['overview'].strip(), allowed)}\n")
    path = f"Maintenance/{today.isoformat()}.md"
    dav.write(path, "\n".join(report))
    found = sum(len(v) for v in issues.values())
    append_log(dav, "lint", f"{len(pages)} pages, {found} code findings, report {path}", day=today)
    return path
