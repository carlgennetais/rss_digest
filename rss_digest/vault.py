import logging
import re
from dataclasses import dataclass
from datetime import datetime, timezone

import httpx

from rss_digest.llm import LLMError
from rss_digest.pages import PageParseError, ai_hash, is_topic_page, new_page, parse_page, render_page
from rss_digest.textutil import normalize_url, safe_filename, strip_md_images, title_key

log = logging.getLogger(__name__)
TOPICS_DIR = "Topics"

ASSIGN_PROMPT = (
    "Assign each numbered article to at least one and at most 2 topics. Reply with JSON mapping every article "
    'number to a list of topic titles: an existing title verbatim, or "NEW: Title" for a new topic. '
    "Tags were set by the reader: treat them as a strong hint, and keep articles that share a tag on the same topic."
)
WRITER_FORMAT = ('\n\nReply with JSON only: {"description": "<one line>", "kind": "entity" or "concept", '
                 '"summary": "<markdown, no ## headings>", "recent": "<markdown bullets>"}\n'
                 'kind: "entity" for a tool, project, company or person; "concept" for an idea, practice or field.\n'
                 "Where it helps the reader, link related topics from the list given, exactly as "
                 "[Title](<File.md>). Never link a topic that is not in the list.")
KINDS = {"entity", "concept"}
_TOPIC_LINK = re.compile(r"\[([^\]]+)\]\(<?([^)>]+?\.md)>?\)")


def keep_known_links(md: str, allowed: set[str]) -> str:
    """Drops links to topic pages that don't exist (keeping their text), so pages never link to nothing."""
    return _TOPIC_LINK.sub(lambda m: m.group(0) if "://" in m.group(2) or m.group(2) in allowed else m.group(1), md)
ITEM_TEXT_CAP = 100_000  # characters per article (about an hour of transcript); 6 of ~1,900 kept items are longer


@dataclass
class TopicRef:
    filename: str
    title: str
    description: str
    kind: str = ""
    sources: int = 0
    updated: str = ""


def list_topics(dav) -> list[TopicRef]:
    topics = []
    for name in dav.list(TOPICS_DIR):
        text = dav.read(f"{TOPICS_DIR}/{name}")
        if text is None or not is_topic_page(text):
            continue
        try:
            front = parse_page(text).front
        except PageParseError:
            continue
        topics.append(TopicRef(name, str(front.get("title") or name.removesuffix(".md")),
                               str(front.get("description") or ""), str(front.get("kind") or ""),
                               len(front.get("sources") or []), str(front.get("updated") or "")))
    return topics


def write_index(dav) -> None:
    """Regenerates Topics/index.md: every topic page with its description, grouped by kind."""
    groups = {"entity": "Entities", "concept": "Concepts", "": "Other"}
    topics = sorted(list_topics(dav), key=lambda t: t.title.casefold())
    out = ["# Index", "", "Generated by rss-digest after every update; edits here are overwritten.", ""]
    for kind, heading in groups.items():
        rows = [t for t in topics if (t.kind if t.kind in groups else "") == kind]
        if rows:
            out += [f"## {heading}", ""] + [
                f"- [{t.title}](<{t.filename}>) — {t.description} · {t.sources} source{'s' * (t.sources != 1)}"
                f" · updated {t.updated}" for t in rows] + [""]
    dav.write(f"{TOPICS_DIR}/index.md", "\n".join(out))

def profile_text(topics: list[TopicRef]) -> str:
    return "\n".join(f"{t.title}: {t.description}" for t in topics)


def _keys(it) -> list[str]:
    """Dedup keys; an empty URL or title says nothing about which article this is."""
    t = title_key(it.title)
    return (["u:" + normalize_url(it.url)] if it.url.strip() else []) + (["t:" + t] if t else [])


def select_new_kept(items, state) -> list:
    seen, out = set(), []
    for it in sorted(items, key=lambda it: -len(it.text)):  # of duplicates, keep the copy with the most text
        keys = _keys(it)
        if state.is_processed(it.id) or any(state.has_key(k) or k in seen for k in keys):
            continue
        seen.update(keys)
        out.append(it)
    return out


def _titles(value, existing: dict[str, str]) -> list[str]:
    vals = value if isinstance(value, list) else [value]
    out = []
    for v in vals[:2]:
        if not isinstance(v, str):
            continue
        t = v.strip()
        if t[:4].lower() == "new:":
            t = t[4:].strip()
        if t:
            out.append(existing.get(t.casefold(), t))
    return out


def _assign(batch, topics, llm, cheap_model) -> dict[str, list]:
    """Returns {item id: [topic titles]}."""
    existing = {t.title.casefold(): t.title for t in topics}
    listing = "\n".join(f"- {t.title}: {t.description}" for t in topics) or "(none)"
    numbered = "\n".join(f"{n}. {it.title} ({it.feed})" + (f" [tags: {', '.join(it.tags)}]" if it.tags else "")
                         for n, it in enumerate(batch, 1))
    reply = llm.chat_json(cheap_model, ASSIGN_PROMPT, f"Existing topics:\n{listing}\n\nArticles:\n{numbered}")
    if not isinstance(reply, dict):
        raise LLMError("assignment reply is not an object")
    wanted: dict[str, list[str]] = {}  # item id -> topic titles
    for key, value in reply.items():
        try:
            n = int(key)
        except ValueError:
            continue
        if not 1 <= n <= len(batch):
            continue
        it = batch[n - 1]
        wanted[it.id] = _titles(value, existing)
    return wanted


def _write_page(title, text, items, dav, state, llm, writer_model, page_prompt, link_targets=None) -> int:
    """Rewrites a topic page with new items; returns how many new items it cites (0: nothing to do).
    link_targets: {"File.md": "Title"} of the other topic pages the writer may link to."""
    path = f"{TOPICS_DIR}/{safe_filename(title)}.md"
    page = new_page(title) if text is None else parse_page(text)
    cited = {normalize_url(s["url"]) for s in page.front["sources"] if s.get("url")}
    items = [i for i in items if normalize_url(i.url) not in cited]
    if not items:  # already on the page: no writer call, no rewrite
        return 0
    links = {f: t for f, t in (link_targets or {}).items() if f != f"{safe_filename(title)}.md"}
    user = (f"Topic: {title}\n\n## Current summary\n{page.summary}\n\n## Current recent changes\n{page.recent}\n\n"
            f"## My notes (read-only context, never rewrite)\n{page.my_notes_tail}\n\n"
            f"## Other topics you may link to\n" + "".join(f"- {t} → {f}\n" for f, t in sorted(links.items()))
            + "\n## New articles\n"
            + "\n\n".join(f"Title: {i.title}\nURL: {i.url}\n{strip_md_images(i.text)[:ITEM_TEXT_CAP]}" for i in items))
    reply = llm.chat_json(writer_model, page_prompt + WRITER_FORMAT, user)
    if not (isinstance(reply, dict) and isinstance(reply.get("summary"), str)
            and isinstance(reply.get("recent"), str)):
        raise LLMError("writer reply needs string summary and recent")
    if isinstance(reply.get("description"), str):
        page.front["description"] = reply["description"]
    if reply.get("kind") in KINDS:
        page.front["kind"] = reply["kind"]
    page.summary = keep_known_links(strip_md_images(reply["summary"]), set(links))
    page.recent = keep_known_links(strip_md_images(reply["recent"]), set(links))
    have = {s.get("url") for s in page.front["sources"]}
    for i in items:
        if i.url not in have:
            have.add(i.url)
            page.front["sources"].append({"url": i.url, "title": " ".join(i.title.split()), "id": i.id,
                                          "date": i.published.date().isoformat()})
    page.front["updated"] = datetime.now(timezone.utc).date().isoformat()
    out = render_page(page)
    dav.write(path, out)
    state.set_page_hash(safe_filename(title), ai_hash(out))
    return len(items)


def write_topic_page(stem: str, title: str, items: list, dav, state, llm, writer_model: str, page_prompt: str,
                     link_targets: dict[str, str] | None = None) -> str:
    """Writes one topic page; returns "written", "flagged" (edited, unparsable or not ours) or "failed"."""
    path = f"{TOPICS_DIR}/{stem}.md"
    try:
        text = dav.read(path)
    except httpx.HTTPStatusError as e:
        log.warning("reading page %s failed, skipping: %s", path, e)
        return "failed"
    if text is not None:
        try:
            bad = not is_topic_page(text) or ai_hash(text) != state.page_hash(stem)
            if not bad:
                parse_page(text)
        except PageParseError:
            bad = True
        if bad:
            log.warning("page %s was edited or is not ours, skipping", path)
            return "flagged"
    try:
        _write_page(title, text, items, dav, state, llm, writer_model, page_prompt, link_targets)
    except (LLMError, httpx.HTTPStatusError) as e:
        log.warning("writing page %s failed, skipping: %s", title, e)
        return "failed"
    return "written"


def mark_kept(items: list, needs: dict[str, set[str]], written: set[str], state) -> None:
    """Marks an item processed once every page it was assigned to is written."""
    for it in items:
        if needs[it.id] <= written:
            state.mark_processed(it.id)
            for k in _keys(it):
                state.add_key(k)


def update_vault(items, dav, state, llm, cheap_model, writer_model, page_prompt, batch_size=20) -> list[str]:
    flagged: list[str] = []
    for start in range(0, len(items), batch_size):
        batch = items[start:start + batch_size]
        try:
            wanted = _assign(batch, list_topics(dav), llm, cheap_model)
        except LLMError as e:
            log.warning("assignment failed, skipping batch: %s", e)
            continue
        by_id = {it.id: it for it in batch}
        pages: dict[str, tuple[str, list]] = {}  # filename stem -> (title, items)
        needs: dict[str, set] = {}  # item id -> filename stems
        for iid, titles in wanted.items():
            for t in titles:
                stem = safe_filename(t)
                pages.setdefault(stem, (t, []))[1].append(by_id[iid])
                needs.setdefault(iid, set()).add(stem)
        done: set[str] = set()
        targets = {t.filename: t.title for t in list_topics(dav)} | {f"{s}.md": t for s, (t, _) in pages.items()}
        for stem, (title, page_items) in pages.items():
            result = write_topic_page(stem, title, page_items, dav, state, llm, writer_model, page_prompt, targets)
            if result == "flagged" and title not in flagged:
                flagged.append(title)
            if result == "written":
                done.add(stem)
                mark_kept(page_items, needs, done, state)  # now, so a budget stop keeps finished items
    return flagged
